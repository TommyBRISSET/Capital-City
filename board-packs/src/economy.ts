export interface SpaceNarrativeInput {
  name: string;
  shortName: string;
  flavorText: string;
  iconKey: string;
}

export function buildBoardPack(params: {
  id: BoardPackId;
  name: string;
  subtitle: string;
  description: string;
  theme: BoardTheme;
  spaceNarratives: readonly SpaceNarrativeInput[];
  eventCards: BoardCardDefinition[];
  communityCards: BoardCardDefinition[];
}): BoardPackDefinition {
  if (params.spaceNarratives.length !== 40) {
    throw new Error(`BoardPack ${params.id} must provide exactly 40 space narratives.`);
  }

  const spaces: BoardSpaceDefinition[] = CANONICAL_40_SPACES_ECONOMY.map((econ, idx) => {
    const narrative = params.spaceNarratives[idx]!;
    return {
      index: econ.index,
      id: `${params.id}-space-${econ.index}`,
      name: narrative.name,
      shortName: narrative.shortName,
      type: econ.type,
      groupCode: econ.groupCode,
      price: econ.price,
      rents: [...econ.rents],
      houseCost: econ.houseCost,
      mortgageValue: econ.mortgageValue,
      taxAmount: econ.taxAmount,
      flavorText: narrative.flavorText,
      iconKey: narrative.iconKey,
    };
  });

  return {
    id: params.id,
    name: params.name,
    subtitle: params.subtitle,
    description: params.description,
    version: '1.0.0',
    language: 'fr',
    theme: params.theme,
    spaces,
    eventCards: params.eventCards,
    communityCards: params.communityCards,
  };
}
